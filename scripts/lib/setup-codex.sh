#!/usr/bin/env bash
# setup-codex.sh — module writers for the `codex` setup target.
#
# Sourced by scripts/setup.sh after platforms/codex/setup.conf. Never executed.
# The module contract is documented in full in scripts/lib/setup-claude.sh.
#
# WHAT THIS TARGET MANAGES
#   ~/.codex/AGENTS.md      the canonical global rules, in a marker block
#   ~/.codex/config.toml    a marker block of COMMENTS ONLY (see below)
#   ~/.codex/rules/tamirs-superpowers.rules
#                           OPTIONAL execpolicy rules, written only when you opt in
#                           (--codex-rules, or `y` at the apply prompt) — see the
#                           execpolicy section below
#
# PERMISSION LEVEL (ADR 004 D7)
#   Codex has no install-time option store, so `setup.sh apply` asks for the
#   plugin's permission level on a terminal when Codex is in scope (the step lives
#   in scripts/lib/setup-common.sh; this file only declares the route).
#
# WHAT IT DELIBERATELY DOES NOT TOUCH — read before adding a module here
#   1. `[hooks]` and every `[hooks.state."..."] trusted_hash` entry. Codex stores
#      a per-hook trust hash there; it is invalidated whenever the hook's content
#      or path changes, and re-trusting is a user action. Rewriting, reordering
#      or reformatting that table would silently break wiring this repo does not
#      own (cmux, gortex, other plugins) with no error the user would ever see.
#      Upstream considers the key a private implementation detail
#      (openai/codex#21615), which is a second reason not to build on it.
#      Our block is appended at EOF and touches nothing above it.
#   2. Real settings of any kind. Under TOML v1.0.0 a bare `key = value` appended
#      at the end of a file binds to the LAST `[table]` header, not to the
#      document root — and config.toml always has tables. Writing `model` or
#      `approval_policy` from here would land them inside `[hooks.state...]`.
#      Every line we write is therefore a comment, which is position-independent.
#      Codex needs no key to load ~/.codex/AGENTS.md; it reads it automatically.

# shellcheck shell=bash

# shellcheck source=scripts/lib/setup-rules-common.sh
. "${SETUP_REPO_ROOT}/scripts/lib/setup-rules-common.sh"

CODEX_REGISTRY_KEY="codex"
CODEX_CATALOG=""
CODEX_RULES_OPT=""      # yes | no | "" (not decided: off)
CODEX_RULES_FILE_NAME="tamirs-superpowers.rules"
CODEX_RULES_HEADER="# tamirs-superpowers Codex execpolicy rules -- generated by scripts/setup.sh"
# Display name is a CONSTANT here, not $SETUP_DISPLAY. The engine re-renders during
# `apply`, after the plan loop has finished and left the target globals pointing at
# whichever target was loaded last — a renderer that reads them writes another
# platform's name into this file.
CODEX_DISPLAY="Codex CLI"

# ---------------------------------------------------------------------------
# agents-md — ~/.codex/AGENTS.md
# ---------------------------------------------------------------------------

codex_agents_md_kind()  { printf 'file'; }
codex_agents_md_label() { printf 'AGENTS.md'; }
codex_agents_md_path()  { printf '%s/AGENTS.md' "$SETUP_TARGET_DIR"; }
codex_agents_md_available() { rules_available; }

codex_agents_md_render()   { rules_md_render "$1" "$CODEX_DISPLAY" "$CODEX_REGISTRY_KEY"; }
codex_agents_md_unrender() { rules_md_unrender "$1"; }
codex_agents_md_destructive() { rules_md_destructive; }
codex_agents_md_summary()  { rules_md_summary "$1"; }

# ---------------------------------------------------------------------------
# config — the comment-only anchor in ~/.codex/config.toml
# ---------------------------------------------------------------------------

codex_config_kind()  { printf 'file'; }
codex_config_label() { printf 'config.toml'; }
codex_config_path()  { printf '%s/config.toml' "$SETUP_TARGET_DIR"; }
codex_config_available() { printf 'yes'; }

codex_config_block_body() {
  cat <<'BODY'
# Global agent rules for Codex live in AGENTS.md next to this file, rendered from
# core/global-rules.md by `bash scripts/setup.sh apply --targets codex`. Codex
# loads that file automatically — no key here enables it.
#
# This block is comments only, on purpose:
#   * Codex records a per-hook `trusted_hash` under [hooks.state.*]. Editing hook
#     content or rewriting that table invalidates the hashes and silently breaks
#     wiring this installer does not own. We never read or write those keys.
#   * Under TOML v1.0.0 a bare `key = value` appended at EOF binds to the last
#     [table] header rather than to the document root, so appending real settings
#     to a file that already has tables is unsafe by construction.
# Your model, approval policy, sandbox and hook settings are left untouched.
BODY
}

codex_config_render()   { rules_toml_render "$1" codex_config_block_body; }
codex_config_unrender() { rules_toml_unrender "$1"; }
codex_config_destructive() { printf 'no'; }
codex_config_summary() { printf 'appends a comment-only block; hooks and trusted_hash untouched'; }

# ---------------------------------------------------------------------------
# permission level route (ADR 004 D7): no install-time option on Codex
# ---------------------------------------------------------------------------

codex_permission_level_route() { printf 'prompt'; }

# ---------------------------------------------------------------------------
# execpolicy — ~/.codex/rules/tamirs-superpowers.rules (OPTIONAL, opt-in)
# ---------------------------------------------------------------------------
#
# WHY IT EXISTS (ADR 004 D8, docs/engineering/research/permissions/platforms/codex.md A6)
#   Codex fails open on a hook `ask`, so the plugin's guard can only deny there,
#   and Codex runs plugin hooks only after `/hooks` trust, re-required on every
#   update. Command rules are a host-side belt the plugin cannot ship (plugins
#   have no rules folder): `prefix_rule(..., decision = "prompt")` makes Codex
#   itself ask before the command forms the plugin NEVER runs automatically.
#
# WHAT IT HOLDS
#   Generated from core/permissions/actions.json: every argv equivalent of an R4
#   id and of an R3 id marked never_auto, whose `cmd` is plain words with no
#   qualifier a prefix cannot express (`any`, `all`, `args`: a flag anywhere, a
#   refspec, a glob). A `none` qualifier is kept: the prefix then also matches the
#   excluded forms, which only asks more. R3 ids on D1's unattended list get no
#   rule, so `unattended` keeps its meaning. Every rule is `prompt`, as D8 says:
#   a human at the Codex prompt can still pass it; nothing passes it silently.
#   REST, GraphQL, MCP and flag-shaped forms stay with the plugin's guard.
#
# CONSENT ("never write global config unasked")
#   Off unless you opt in: --codex-rules / SETUP_CODEX_RULES=1, or `y` at the
#   apply prompt on a terminal. A file this installer generated earlier counts as
#   that opt-in, so `apply` keeps it current (through the usual diff and confirm);
#   --no-codex-rules leaves it as it is; `remove` deletes it. A file of the same
#   name you wrote yourself is never deleted, and replacing it asks first.
#   Codex documents rules as EXPERIMENTAL; the prompt says so.

codex_execpolicy_kind()  { printf 'file'; }
codex_execpolicy_label() { printf 'rules/*.rules'; }
codex_execpolicy_path()  { printf '%s/rules/%s' "$SETUP_TARGET_DIR" "$CODEX_RULES_FILE_NAME"; }

# codex_execpolicy_ours <file> — the file's first line is our header.
codex_execpolicy_ours() {
  local first=""
  [ -f "$1" ] || return 1
  IFS= read -r first < "$1" || [ -n "$first" ] || return 1
  [ "$first" = "$CODEX_RULES_HEADER" ]
}

codex_target_init() {
  local ans
  CODEX_CATALOG="${SETUP_REPO_ROOT}/core/permissions/actions.json"
  case "$(setup_lower "${SETUP_CODEX_RULES:-}")" in
    1|y|yes|true|on) CODEX_RULES_OPT=yes ;;
    0|n|no|false|off) CODEX_RULES_OPT=no ;;
    *) CODEX_RULES_OPT="" ;;
  esac
  if [ -z "$CODEX_RULES_OPT" ] && codex_execpolicy_ours "$(codex_execpolicy_path)"; then
    CODEX_RULES_OPT=yes
  fi
  # Ask once, only on an interactive apply that would plan this module at all.
  if [ -z "$CODEX_RULES_OPT" ] && [ "${SETUP_INTERACTIVE_APPLY:-}" = yes ] && setup_can_prompt \
     && { ! type module_selected >/dev/null 2>&1 || module_selected execpolicy; }; then
    {
      printf '\n%sCodex execpolicy rules — EXPERIMENTAL in Codex%s (optional, off by default)\n' "$SETUP_C_BOLD" "$SETUP_C_OFF"
      printf '  Writes %s, a file you own, so that\n' "$(setup_tilde "$(codex_execpolicy_path)")"
      printf '  Codex itself asks before the commands this plugin never runs automatically\n'
      printf '  (releases, repository create/delete, direct merges, agent spawns, docker, ...).\n'
      printf '  A belt for when the plugin'"'"'s hooks are not trusted yet; Codex documents rules as\n'
      printf '  experimental, so their behaviour can change between Codex releases.\n'
      printf '  Undo: bash scripts/setup.sh remove --targets codex --only execpolicy\n'
    } >&2
    # Into a variable, never `$(setup_ask ...)`: inside a command substitution
    # stdout is the capture pipe, so the prompt would decide "no terminal" and
    # hand back the default without asking (setup-common.sh, setup_ask_into).
    setup_ask_into ans 'Write the Codex rules file? [y/N] ' n
    ans="$(setup_lower "$ans")"
    case "$ans" in y|yes) CODEX_RULES_OPT=yes ;; *) CODEX_RULES_OPT=no ;; esac
  fi
  case " $SETUP_MODULES " in
    *" execpolicy "*) ;;
    *) SETUP_MODULES="$SETUP_MODULES execpolicy" ;;
  esac
}

codex_execpolicy_available() {
  if [ "${VERB:-}" = remove ]; then printf 'yes'; return 0; fi
  if [ ! -f "$CODEX_CATALOG" ]; then
    printf 'no:core/permissions/actions.json not found in this checkout'; return 0
  fi
  case "$CODEX_RULES_OPT" in
    yes) printf 'yes' ;;
    no) printf 'no:off (declined, or --no-codex-rules)' ;;
    *) printf 'no:off — opt in with --codex-rules (Codex marks rules experimental)' ;;
  esac
}

# codex_execpolicy_rules — the prefix_rule() calls, one per distinct prefix, in a
# stable order (jq group_by sorts), so a second apply is byte-identical.
codex_execpolicy_rules() {
  jq -r '
    [ .actions[]
      | select(.r >= 4 or (.r == 3 and .never_auto == true))
      | . as $a
      | ($a.equivalents.argv // [])[]
      | select(type == "object" and has("cmd") and (((keys - ["cmd", "none"]) | length) == 0))
      | select((.cmd | length) > 0 and all(.cmd[]; type == "string" and test("^[A-Za-z0-9._@/+-]+$")))
      | {cmd: .cmd, id: $a.id, r: $a.r} ]
    | group_by(.cmd)[]
    | "prefix_rule(\n"
      + "    pattern = [" + (.[0].cmd | map(@json) | join(", ")) + "],\n"
      + "    decision = \"prompt\",\n"
      + "    justification = " + ("tamirs-superpowers: " + (map(.id + " (R" + (.r | tostring) + ")") | unique | join(", "))
          + " never runs automatically at any level (ADR 004 D1)" | @json) + ",\n"
      + ")\n"
  ' "$CODEX_CATALOG"
}

codex_execpolicy_render() {
  printf '%s\n' "$CODEX_RULES_HEADER"
  cat <<'HEAD'
#
# EXPERIMENTAL: Codex documents command rules (execpolicy) as experimental.
#
# You own this file; the plugin never ships or edits it (plugins cannot carry
# rules). It is generated from the plugin's action catalog,
# core/permissions/actions.json (ADR 004 D7, D8): every command form the plugin
# never runs automatically gets a `prompt` rule, so Codex asks you before it runs,
# whether or not the plugin's hooks are trusted yet.
#
# A prefix rule matches every command that STARTS with its pattern, so it also
# asks for longer forms the plugin treats differently (`gh pr merge` asks for
# `gh pr merge --auto` too). Forms a prefix cannot express (a flag anywhere,
# refspecs, REST/GraphQL calls, MCP tools) stay with the plugin's own guard.
# Codex's own "always allow" answers go to default.rules, not here.
#
# Refresh: bash scripts/setup.sh apply --targets codex --only execpolicy
# Remove:  bash scripts/setup.sh remove --targets codex --only execpolicy
# Check:   codex execpolicy check --rules <this file> -- gh release create v1
HEAD
  printf '\n'
  codex_execpolicy_rules
}

# remove deletes only a file this installer generated; anything else stays.
codex_execpolicy_unrender() {
  local existing="$1"
  [ -f "$existing" ] || return 0
  if codex_execpolicy_ours "$existing"; then printf '%s' "$SETUP_DELETE_SENTINEL"
  else cat "$existing"; fi
}

codex_execpolicy_destructive() {
  if [ -f "$1" ] && ! codex_execpolicy_ours "$1"; then printf 'yes'; else printf 'no'; fi
}

codex_execpolicy_summary() {
  local n
  n="$(grep -c '^prefix_rule(' "$2" 2>/dev/null || printf 0)"
  printf '%s prompt rule(s) for never-automatic commands (experimental)' "$n"
}
