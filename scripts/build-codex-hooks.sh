#!/usr/bin/env bash
# build-codex-hooks.sh — generate the Codex hooks file from the canonical hooks file.
#
# Usage:
#   bash scripts/build-codex-hooks.sh [repo-root] [--check] [--verbose]
#   bash scripts/build-codex-hooks.sh -h | --help
#
# Generates:
#   platforms/codex/hooks.json  — from hooks/hooks.json
#
# --check regenerates into a temp dir and diffs, so CI can fail on drift without
# writing to the working tree.
#
# WHY THIS EXISTS
#   Codex loads a plugin's hooks file natively and exports CLAUDE_PLUGIN_ROOT for
#   compatibility, so the plugin pointed its Codex manifest straight at the Claude
#   file. Then 4.10.0 added a top-level `modules` key to that file to load the mod.
#   Codex's hooks-file parser is strict at the top level: it accepts exactly
#   `description` and `hooks` and rejects a file with any other key. Source-read, not
#   run live, but either way no plugin hook runs on Codex from a file that carries
#   `modules`. Codex therefore gets a generated copy without it, and the Codex manifests
#   point there. Since 5.0.2 the key lives in mod/modules.json (the plugin directory holds
#   every script that reaches a folder holding the file that names the mod), so the
#   canonical file normally carries no `modules` at all; the generator still drops one.
#
# WHAT IS DROPPED, AND WHY
#   - `modules`: the Claude Code mod loader; Codex runs no mod and its parser rejects
#     the key.
#   - the events Codex has no equivalent for: Notification, DirectoryAdded,
#     WorktreeCreate, WorktreeRemove, StopFailure. Codex's event table is not strict,
#     so it would ignore them; they are dropped so that what the file declares is what
#     Codex runs, and so that a reviewer trusting hooks in Codex reviews only hooks that
#     can fire.
#   - `onFailure` on every hook entry. It is Claude's key: Codex's command-hook struct
#     has no such field, so Codex cannot honour "block when the hook fails". The guards
#     (worktree isolation, sensitive files, branch concurrency, Docker state) are
#     therefore FAIL-OPEN on Codex: a guard that crashes or times out lets the action
#     through. The Codex install doc says so.
#
# WHAT IS KEPT
#   `${CLAUDE_PLUGIN_ROOT}` in every command: Codex exports it for compatibility, so
#   the commands run unmodified. `timeout` and `statusMessage` are fields Codex's
#   command hook accepts under the same names. The twelve events Codex supports are
#   SessionStart, SessionEnd, SubagentStart, UserPromptSubmit, PreToolUse,
#   PermissionRequest, PostToolUse, PreCompact, PostCompact, SubagentStop, Stop and
#   Interrupt; the generator keeps whichever of them the canonical file wires and adds
#   none, since a Codex-only event with no handler here is not a hook.
#
# Exit 0 on success; 1 if --check finds drift; 2 on a malformed source or a command
# whose script is missing.
set -euo pipefail

usage() { sed -n '2,13p' "$0" | sed 's/^#[[:space:]]\{0,1\}//'; exit "${1:-0}"; }

ROOT="."
CHECK=false
VERBOSE=false
for arg in "$@"; do
  case "$arg" in
    -h|--help) usage 0 ;;
    --check) CHECK=true ;;
    -v|--verbose) VERBOSE=true ;;
    -*) printf 'Unknown flag: %s\n' "$arg" >&2; usage 1 ;;
    *) ROOT="$arg" ;;
  esac
done
ROOT="$(cd "$ROOT" && pwd)"

command -v python3 >/dev/null 2>&1 || { printf 'error: python3 is required (it renders the JSON)\n' >&2; exit 2; }
[[ -f "$ROOT/hooks/hooks.json" ]] || { printf 'error: no hooks/hooks.json under %s\n' "$ROOT" >&2; exit 2; }

OUT=platforms/codex/hooks.json
DEST="$ROOT"
if [[ "$CHECK" == true ]]; then
  DEST="$(mktemp -d)"
  trap 'rm -rf "$DEST"' EXIT
fi

python3 - "$ROOT" "$DEST/$OUT" "$VERBOSE" <<'PY' || exit 2
import json, os, re, sys

root, out, verbose = sys.argv[1], sys.argv[2], sys.argv[3] == "true"
src = os.path.join(root, "hooks", "hooks.json")
with open(src, encoding="utf-8") as f:
    try:
        canon = json.load(f)
    except ValueError as e:
        sys.exit("error: hooks/hooks.json is not valid JSON: %s" % e)

SUPPORTED = ["SessionStart", "SessionEnd", "SubagentStart", "UserPromptSubmit", "PreToolUse",
             "PermissionRequest", "PostToolUse", "PreCompact", "PostCompact", "SubagentStop",
             "Stop", "Interrupt"]
DROPPED_EVENTS = ["Notification", "DirectoryAdded", "WorktreeCreate", "WorktreeRemove", "StopFailure", "TaskCompleted", "TeammateIdle"]

DESCRIPTION = (
    "Generated by scripts/build-codex-hooks.sh from hooks/hooks.json - do not edit; "
    "regenerate with `bash scripts/build-codex-hooks.sh .`. Codex parses a hooks file with "
    "exactly two top-level keys (description, hooks), so the Claude `modules` entry that "
    "loads the mod is left out. The events Codex has no equivalent for (" + ", ".join(DROPPED_EVENTS) +
    ") are left out. Claude's per-hook `onFailure` is left out because Codex's command hook "
    "has no such field, so every guard is fail-open on Codex: a guard that crashes or times "
    "out lets the action through. ${CLAUDE_PLUGIN_ROOT} is kept because Codex exports it for "
    "compatibility."
)

errors = []
hooks_in = canon.get("hooks")
if not isinstance(hooks_in, dict):
    sys.exit("error: hooks/hooks.json has no `hooks` object")

hooks_out = {}
dropped = []
for event, groups in hooks_in.items():
    if event not in SUPPORTED:
        if event not in DROPPED_EVENTS:
            errors.append("hooks/hooks.json wires %s, an event neither Codex's list nor the known-dropped list names; add it to one in this script" % event)
        dropped.append(event)
        continue
    out_groups = []
    for g in groups:
        og = {}
        for k, v in g.items():
            if k == "hooks":
                og[k] = []
                for h in v:
                    h2 = {hk: hv for hk, hv in h.items() if hk != "onFailure"}
                    # Codex clamps SessionEnd and Interrupt hooks to 3 s and reports a larger
                    # timeout as an error item every session (measured on 0.163.0); write the
                    # clamp so the generated file is quiet.
                    if event in ("SessionEnd", "Interrupt") and isinstance(h2.get("timeout"), (int, float)) and h2["timeout"] > 3:
                        h2["timeout"] = 3
                    og[k].append(h2)
            else:
                og[k] = v
        out_groups.append(og)
    hooks_out[event] = out_groups

# Every command's script must exist. The shape is `<interp> "${CLAUDE_PLUGIN_ROOT}"/path`
# or `<interp> "${CLAUDE_PLUGIN_ROOT}/path"`; both resolve against the plugin root.
for event, groups in hooks_out.items():
    for g in groups:
        for h in g.get("hooks", []):
            if h.get("type") != "command":
                errors.append("%s: hook type %r is not a command; Codex skips prompt/agent hooks" % (event, h.get("type")))
                continue
            m = re.search(r'\$\{CLAUDE_PLUGIN_ROOT\}"?/([^ "]+)', h.get("command", ""))
            if not m:
                errors.append("%s: command %r does not run a script under ${CLAUDE_PLUGIN_ROOT}" % (event, h.get("command")))
            elif not os.path.isfile(os.path.join(root, m.group(1))):
                errors.append("%s: command names %s, which does not exist in this tree" % (event, m.group(1)))

if errors:
    sys.exit("\n".join("error: " + e for e in errors))

result = {"description": DESCRIPTION, "hooks": hooks_out}
os.makedirs(os.path.dirname(out), exist_ok=True)
with open(out, "w", encoding="utf-8") as f:
    f.write(json.dumps(result, indent=2, ensure_ascii=False) + "\n")
if verbose:
    print("kept events: " + ", ".join(hooks_out))
    print("dropped events: " + (", ".join(dropped) or "none"))
PY

if [[ "$CHECK" == true ]]; then
  if [[ ! -f "$ROOT/$OUT" ]]; then
    printf 'DRIFT: %s is missing from the tree\n' "$OUT" >&2
  elif diff -u "$ROOT/$OUT" "$DEST/$OUT" >&2; then
    printf 'codex hooks: %s matches hooks/hooks.json\n' "$OUT"
    exit 0
  fi
  printf 'DRIFT: %s differs from what hooks/hooks.json generates. Regenerate: bash scripts/build-codex-hooks.sh .\n' "$OUT" >&2
  exit 1
fi
printf 'codex hooks: wrote %s\n' "$OUT"
