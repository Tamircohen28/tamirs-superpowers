#!/usr/bin/env bash
# PreToolUse guard: block writes to genuinely generated / protected files.
#
# Two classes, judged in this order (ADR 004 D10):
#   1. PROTECTED (R4 `policy.edit`, `config.global.write`): the plugin's own
#      permission files and state dir (from the passwd entry, never HOME/XDG),
#      a project's .tamirs-superpowers/, the guard files of the running plugin,
#      the installed plugin cache, and every host settings / option store that
#      could widen what an agent may do. The table is core/permissions/
#      actions.json. Denied; NO environment switch unlocks them, because the
#      agent must never edit its own policy (D10.3). Guard files of a running
#      plugin that is a source checkout are an R4 ask instead (contributors
#      edit them), through hook_ask where the platform has one, else a deny.
#      Targets are judged by realpath too, and an unresolved write whose text
#      names a protected path is a deny (S-03) — the text that could steer it,
#      not a read-only command's arguments or data written to a file (#402).
#   2. GENERATED (lockfiles, .yarn/releases, shadcn UI, ignored build output).
#      The user may set PM_ALLOW_PROTECTED=1 to edit one on purpose; it is
#      theirs to set and no deny text names it (D10.5). GitHub Actions
#      workflows left this class in 5.6.7: agents may edit them.
#   Paths are compared case-folded on a case-insensitive volume (macOS APFS):
#   the parser repeats each target under its on-disk spelling, and folds its
#   own protected rules wherever the volume folds or cannot be shown not to.
#
# WHY THIS KEYS ON THE PATH BEING WRITTEN, NOT THE TOOL DOING THE WRITING
#   Until 2026-08-31 this hook was wired to `Edit|Write|MultiEdit|…` and read a
#   `file_path` out of the payload. So it asked "is a file-editing TOOL touching
#   this path?" when the question it exists to answer is "is this path being
#   modified?". `Bash` sits between the two — `cat > f <<EOF`, `sed -i`, `tee`,
#   `cp` — and in that gap the guard's silence read as a pass. Worse, the actor
#   the guard exists to constrain is an agent, and agents have Bash: the bypass
#   was available to precisely the wrong party, by default, with no intent to
#   circumvent. An agent that simply preferred Bash never saw the guard and
#   never learned the file was protected.
#
#   The decision now runs over WRITE TARGETS, whatever produced them.
#   the write-targets helper parses the command and reports only operands in a
#   writing position; a protected path mentioned in a `grep` pattern, a commit
#   message or a heredoc body is never a target, so the false-positive class
#   already on record for `docker-guard.py` (which matches command text) does
#   not apply here. Where a target cannot be resolved statically the parser says
#   UNSURE and this hook surfaces that rather than falling silent — see
#   "WHAT THIS STILL CANNOT SEE" below.
#
# WHY THE RULES MATCH SIGNALS, NOT PATH SHAPES
#   The first version denied a fixed glob list that included `*/dist/*`,
#   `*/build/*` and `*/src/components/ui/*`, explaining the last one as
#   "generated shadcn UI". In any repo that does not use shadcn, that path is
#   ordinary hand-written source — and a repo that commits its `dist/` (a
#   published bundle, a Go binary, a docs site) has a tracked directory, not
#   build output. So the guard blocked real work and offered a remedy
#   ("regenerate via the shadcn CLI") that did not exist there.
#
#   Each rule below names the fact it read:
#     - lockfiles           : generated by a package manager, in every repo
#     - .yarn/releases/*    : a vendored yarn binary, in every repo that has one
#     - dist/ build/ out/   : blocked ONLY when git itself ignores the path
#     - src/components/ui/* : blocked ONLY when components.json (shadcn) exists
#
# WHAT THIS STILL CANNOT SEE — stated because a believed-closed gap is worse
# than a known one:
#   - Code run inside an interpreter (`python3 -c`, `node -e`, a string the shell evaluates, a pipe into a shell,
#     a heredoc piped to a shell) writes in a language this parser does not
#     read. Reported as UNSURE, never silently allowed.
#   - Targets built at runtime (`> "$OUT"`, `xargs`, `find -exec`, a glob) and
#     a patch it cannot read now (piped in, or rewritten earlier in the same
#     command). Also UNSURE. A readable patch is read: its target headers are
#     the targets. A variable assigned a LITERAL earlier in the same command
#     (`S=/tmp/x; cp a "$S/b"`) is resolved, so that write is checked, and
#     `S=/tmp/x; cp a "$S/package-lock.json"` is a block; a value built by a
#     substitution, or assigned where it might not run, stays UNSURE (#336).
#   - Every UNSURE kind is explained once per session; a repeat is one line
#     naming the unresolved target (#336, below).
#   - Ordinary programs that happen to write (`make`, `npm install`, a checked-in
#     script, `awk -f prog`). NOT reported: at that breadth the warning fires on
#     everything and means nothing, and the tool-level guard never covered them.
#     They ARE reported (UNSURE) when they run a file the same command wrote, a
#     command name built by expansion, a runner the parser does not unwrap
#     (`strace`, `ssh`, `docker run`, …) or a command named in an environment
#     variable (`GIT_EXTERNAL_DIFF=…`); the commands inside `$(…)`, backticks
#     and `<(…)`/`>(…)` are parsed as commands of their own (issue #405).
#   - Metadata-only changes (`chmod`, `chown`), git aliases, and a write through
#     a hard link made before this call. git's replays (checkout, switch,
#     restore, reset --hard, merge, pull, rebase, cherry-pick, revert, am,
#     stash) are judged against the PROTECTED paths by the files git says they
#     change, as an R4 ask (hook_ask on Claude Code, a deny on every other host:
#     an integrator merging a branch legitimately brings such a file in, and the
#     user decides); they never meet the generated-file rules, since a merge
#     legitimately rewrites a lockfile.
#   The half that closes those is a git/CI check on the modified path — it sees
#   the outcome rather than the mechanism, so no choice of tool routes around
#   it. This hook is the fast-feedback half, not the binding one.
set -uo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=lib/hook-output.sh
source "${SCRIPT_DIR}/lib/hook-output.sh"

input="$(hook_read_stdin)"
hook_detect_platform "$input"

[ -z "$input" ] && hook_pass

# nearest_existing_dir DIR — walk up from DIR to the nearest ancestor that
# actually exists. `git -C` on a directory that does not exist yet fails
# silently (repo_root resolves to "", and every check below gated on
# `[ -n "$repo_root" ]` then quietly no-ops), which let a write into a
# not-yet-created directory — e.g. a first file under a new
# src/components/ui/ or a gitignored dist/ — slip past the shadcn and
# build-output rules entirely. A brand-new file's directory need not exist
# for the file's REPO to be resolvable; walking up to the nearest real
# ancestor finds it. Same approach as enforce-worktree-edits.sh's helper of
# the same name, kept local here since this script doesn't source that one.
nearest_existing_dir() {
  local d="$1"
  while [[ -n "$d" && "$d" != "/" && "$d" != "." && ! -d "$d" ]]; do
    d="$(dirname "$d")"
  done
  # A here-string adds a newline; the caller's $( ) strips it again.
  cat <<<"$d"
}

# TARGET <tab> <abs path> <tab> <fragment>   — a file this call will write
# DELETE <tab> <abs path> <tab> <fragment>   — a file or tree this call removes
# TREE   <tab> <abs path> <tab> <fragment>   — a path a copy/move/extraction fills
# UNSURE <tab> <why>      <tab> <fragment>   — a write this parse cannot resolve
# PROTECTED <tab> deny|ask <tab> <why>           — an R4 path (--protected)
analysis="$(python3 "${SCRIPT_DIR}/lib/write-targets.py" --protected 2>/dev/null <<<"$input")"

deny() {
  local reason="$1"
  echo "$reason" >&2
  hook_deny "$reason"
}

# The R4 remedy (D10.3, D10.5): only the user changes these, outside the
# agent's reach. It names no bypass — not an env switch, not another tool.
PROTECTED_REMEDY="Only the user changes plugin permission policy, guard files and host settings (ADR 004 D10): stop and ask them to make this change themselves, outside this session. Do not retry it through another tool, command or path."
# A block judged from the command's TEXT (an unresolved write, or code this
# parse cannot read, that names a protected path) is not proof of a write
# (issue #402). It keeps the same rule for a real write, and otherwise asks
# for a command the guard can resolve, which is then judged on its target.
MENTION_REMEDY="Only the user changes plugin permission policy, guard files and host settings (ADR 004 D10): if this command does write that path, stop and ask them to make the change themselves. If it does not, rewrite it so the guard can resolve its target, for example a literal path in place of a variable or inline code."

protected_ask() {
  local reason="$1"
  if declare -F hook_ask >/dev/null 2>/dev/null; then
    echo "$reason" >&2
    hook_ask "$reason"
  fi
  # No host ask here: an R4 ask the platform cannot deliver is a deny (D8).
  deny "$reason"
}

# classify <abs path> <fragment> <TARGET|DELETE|TREE> — deny (and exit) if protected.
# With PM_ALLOW_PROTECTED=1 none of these rules is judged (see the header).
classify() {
  local file="$1" via="$2" kind="$3" repo_root context=""
  [ -n "$file" ] || return 0
  [ -n "$via" ] && context=" (via: $via)"

  # A GitHub Actions workflow is ordinary, reviewable source (5.6.7, the user's decision of
  # 2026-11-06): agents edit workflows in every repo, the change lands in a commit and a PR
  # like any other, and git undoes it. The remote route (`gh api .../contents/.github/
  # workflows/...`) is still judged by permission-guard.sh as workflow.edit.
  [ "$override" = "1" ] && return 0

  # Repo root for the file being written — every derived check below needs
  # it. Resolved from the nearest EXISTING ancestor of the file's directory,
  # not the directory itself, so a write that creates a new directory (a
  # first file under src/components/ui/, a fresh dist/ output) still gets
  # judged instead of silently skipping every repo_root-gated rule.
  repo_root="$(git -C "$(nearest_existing_dir "$(dirname "$file")")" rev-parse --show-toplevel 2>/dev/null || true)"

  case "$file" in
    *.lock|*/package-lock.json|*/pnpm-lock.yaml|*/bun.lockb|*/go.sum)
      deny "BLOCKED: '$file' is a package-manager lockfile — it is generated, never hand-edited.$context Change the manifest (package.json / Cargo.toml / pyproject.toml / go.mod) and re-run the package manager so the lockfile is regenerated."
      ;;
    */.yarn/releases/*)
      deny "BLOCKED: '$file' is the vendored Yarn binary under .yarn/releases/.$context Change it with 'yarn set version <version>', not by editing the file."
      ;;
    */src/components/ui/*|*/components/ui/*)
      # The only honest signal that this directory is generated is a shadcn
      # config. Without it, this is hand-written source in a conventional place.
      if [ -n "$repo_root" ] && [ -f "$repo_root/components.json" ]; then
        deny "BLOCKED: '$file' sits under components/ui/ in a shadcn project (detected: $repo_root/components.json) — these files are generated.$context Re-generate with the shadcn CLI's add command, or move your customisation into a wrapper component outside components/ui/."
      fi
      ;;
    */dist/*|*/build/*|*/out/*|*/.next/*|*/target/debug/*|*/target/release/*)
      # Blocked only when git ignores it — a committed dist/ is a deliberate
      # artifact directory, not build output this hook should defend. And only
      # for content: this rule's whole argument is "your edit is discarded by
      # the next build", which is not a reason to stop `rm -rf dist/`.
      if [ "$kind" != "DELETE" ] && [ -n "$repo_root" ] && git -C "$repo_root" check-ignore -q -- "$file" 2>/dev/null; then
        deny "BLOCKED: '$file' is build output — git ignores this path in $repo_root, so it is regenerated by the build and any edit here is discarded.$context Change the source and re-run the build."
      fi
      ;;
  esac
  return 0
}

# A here-string, not a pipe: `deny` must be able to exit THIS shell. In a
# pipeline the loop is a subshell, `exit` leaves it, and the script would fall
# through and print a second, contradictory pass. The here-string feeds the
# same bytes the old `< <(printf '%s\n' …)` did: the text plus one newline.
#
# Pass 1 — protected paths, before and regardless of PM_ALLOW_PROTECTED.
# Every deny outranks every ask, so the asks wait for the whole list.
ask_reason=""
while IFS=$'\t' read -r kind mode why; do
  [ "$kind" = "PROTECTED" ] || continue
  case "$mode" in
    ask) [ -n "$ask_reason" ] || ask_reason="$why" ;;
    *)   case "$why" in
           *"is treated as a write to it."*) deny "BLOCKED: $why $MENTION_REMEDY" ;;
           *)                                deny "BLOCKED: $why $PROTECTED_REMEDY" ;;
         esac ;;
  esac
done <<<"$analysis"
if [ -n "$ask_reason" ]; then
  # The reason says why this is an ask (a source checkout's guard file, or a
  # git replay onto a protected path); write-targets.py words it.
  protected_ask "R4 ASK: $ask_reason"
fi

# Claude Code's bypass mode (5.6.7): the user chose to run free, so the generated-file
# rules below step aside. They guard edits that git can undo; pass 1 above
# (the plugin's own policy, guard files and host settings) still holds. The mode comes from
# the host's own payload (hook_host_bypass), never from an environment variable.
hook_host_bypass "$input" && hook_pass

# Pass 2 — generated files. The user's override applies to all of them.
override=0
[ "${PM_ALLOW_PROTECTED:-0}" = "1" ] && override=1

# Each KIND of unresolved write is explained in full once per session (#336).
# The explanation is the same hundred tokens every time; in one measured
# session it was injected about sixty times, none of them a block, and buried
# the two real blocks. A repeat still says the write was not checked — that is
# the no-silent-failure property — in one line that names the unresolved
# target, without the paragraph. The key is the reason with its per-command
# detail (the `(…)` tail) stripped, so `$OUT` and `$S/b` are one kind; the
# marker is a file per (session, kind) under the plugin's data directory
# (TMPDIR when the host exports none), per user, swept after two days. No
# session id means no marker and the full notice every time.
notice_dir=""
session_key="$(jq -r '.session_id // .conversation_id // empty' <<<"$input" 2>/dev/null || true)"
session_key="${session_key//[^a-zA-Z0-9_-]/_}"
if [ -n "$session_key" ]; then
  notice_base="${CLAUDE_PLUGIN_DATA:-${TMPDIR:-/tmp}}"
  notice_base="${notice_base%/}/guard-sensitive-files/notices-$(id -u)"
  notice_dir="${notice_base}/${session_key}"
fi
# notice_marker <reason> — the marker path for this session and reason kind.
notice_marker() {
  local kind="${1%% (*}" sum
  sum="$(cksum <<<"$kind" | cut -d' ' -f1)"
  echo "${notice_dir}/${sum}"
}

unsure=""
repeats=""
new_markers=()
while IFS=$'\t' read -r kind detail fragment; do
  case "$kind" in
    TARGET|DELETE|TREE) classify "$detail" "$fragment" "$kind" ;;
    UNSURE)
      case "$unsure$repeats" in *"$detail"*) continue ;; esac   # once per command too
      if [ -n "$notice_dir" ] && [ -f "$(notice_marker "$detail")" ]; then
        repeats="${repeats:+${repeats}; }${detail}"
      else
        unsure="${unsure}  - ${detail}"$'\n'
        [ -n "$notice_dir" ] && new_markers+=("$(notice_marker "$detail")")
      fi
      ;;
  esac
done <<<"$analysis"

# The unresolved-write notice is advisory, never a block: the command still runs either way,
# and a write the parse *can* resolve to a protected path is still denied above. Off by default
# since 5.6.3 (the user found it noise on every inline script); the plugin option
# unresolved_write_notices turns it back on, and then "could not determine" is never delivered
# as "no protected file was touched".
case "${CLAUDE_PLUGIN_OPTION_UNRESOLVED_WRITE_NOTICES:-false}" in
  true|1|yes|on) ;;
  *) unsure=""; repeats=""; new_markers=() ;;
esac
if [ -n "$unsure" ]; then
  if [ "${#new_markers[@]}" -gt 0 ]; then
    mkdir -p "$notice_dir" 2>/dev/null && chmod 700 "$notice_base" "$notice_dir" 2>/dev/null
    for marker in "${new_markers[@]}"; do : > "$marker" 2>/dev/null || true; done
    find "$notice_base" -mindepth 1 -maxdepth 1 -type d -mtime +2 -exec rm -rf {} + 2>/dev/null || true
  fi
  [ -n "$repeats" ] && unsure="${unsure}  - (same unresolved-write notice as earlier this session: ${repeats})"$'\n'
  hook_additional_context "PROTECTED-FILE GUARD: this command writes somewhere it could not resolve statically, so it was NOT checked against the protected-path rules:
${unsure}If it writes a lockfile, .yarn/releases/, generated shadcn UI, or gitignored build output, that is on you — rewrite it with a literal path so the guard can see the target, or ask the user before proceeding."
elif [ -n "$repeats" ]; then
  hook_additional_context "PROTECTED-FILE GUARD: unresolved write, not checked (same notice as earlier this session): ${repeats}"
fi

hook_pass
