  *) exit 0 ;;
esac
PI_EVENT="$_pi_event" python3 -I -S -c "$_PI_PY" "$PI_ROOT" "${HOOK_PLATFORM:-claude}" 3<<<"$_PERM_ENGINE" <<<"$input" 2>/dev/null
exit 0
